"use strict";

// Preserve the synchronous SQLite-shaped interface used by this small app while
// moving hosted data to Postgres. A dedicated worker owns one client so
// transactions remain on the same connection; Atomics lets the main thread
// wait for each operation without blocking the worker's network loop.
const path = require("node:path");
const { Worker } = require("node:worker_threads");

const BUFFER_BYTES = 8 * 1024 * 1024;

class PostgresSyncDatabase {
  constructor(connectionString) {
    this.shared = new SharedArrayBuffer(BUFFER_BYTES);
    this.state = new Int32Array(this.shared, 0, 2);
    this.bytes = new Uint8Array(this.shared, 8);
    this.worker = new Worker(path.join(__dirname, "postgres-worker.js"), {
      workerData: { connectionString, shared: this.shared }
    });
    const ready = Atomics.wait(this.state, 0, 0, 20000);
    if (ready === "timed-out") throw new Error("Timed out connecting to the hosted PostgreSQL database.");
    if (Atomics.load(this.state, 0) !== 1) throw new Error(this.readResponse() || "Could not connect to PostgreSQL.");
  }

  readResponse() {
    const length = Atomics.load(this.state, 1);
    if (length < 0 || length > this.bytes.length) return "The database returned an oversized response.";
    return Buffer.from(this.bytes.subarray(0, length)).toString("utf8");
  }

  request(payload) {
    Atomics.store(this.state, 0, 0);
    Atomics.store(this.state, 1, 0);
    this.worker.postMessage(payload);
    const result = Atomics.wait(this.state, 0, 0, 20000);
    if (result === "timed-out") throw new Error("The hosted PostgreSQL query timed out.");
    const response = this.readResponse();
    if (Atomics.load(this.state, 0) < 0) throw new Error(response || "The hosted PostgreSQL query failed.");
    return response ? JSON.parse(response) : null;
  }

  exec(sql) {
    const statement = String(sql).trim();
    if (!statement || /^PRAGMA\b/i.test(statement) || /\bCREATE\s+TRIGGER\b/i.test(statement)) return;
    this.request({ mode: "exec", sql: normalizeSql(statement) });
  }

  prepare(sql) {
    const source = String(sql).trim();
    return {
      get: (...params) => this.request({ mode: "get", sql: normalizeSql(source), params: normalizeParams(source, params) }) || undefined,
      all: (...params) => this.request({ mode: "all", sql: normalizeSql(source), params: normalizeParams(source, params) }) || [],
      run: (...params) => this.request({ mode: "run", sql: normalizeSql(source), params: normalizeParams(source, params) }) || { changes: 0 }
    };
  }

  close() {
    this.worker.terminate();
  }
}

function normalizeParams(sql, params) {
  if (/PRAGMA\s+table_info/i.test(sql)) return [];
  return params;
}

function normalizeSql(sql) {
  let statement = sql
    .replace(/\bBEGIN\s+IMMEDIATE\b/gi, "BEGIN")
    .replace(/\bMAX\s*\(/gi, "GREATEST(")
    .replace(/\bemail\s*=\s*\?\s+COLLATE\s+NOCASE/gi, "LOWER(email) = LOWER(?)")
    .replace(/\bemail\s*<>\s*\?\s+COLLATE\s+NOCASE/gi, "LOWER(email) <> LOWER(?)")
    .replace(/\bCOLLATE\s+NOCASE\b/gi, "")
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");

  const ignoreInsert = /^INSERT\s+OR\s+IGNORE\s+INTO\b/i.test(statement);
  if (ignoreInsert) statement = statement.replace(/^INSERT\s+OR\s+IGNORE\s+INTO\b/i, "INSERT INTO");

  const pragmaInfo = statement.match(/^PRAGMA\s+table_info\((\w+)\)$/i);
  if (pragmaInfo) {
    const tableName = pragmaInfo[1].toLowerCase();
    statement = "SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '" + tableName + "'";
  }
  if (/ALTER\s+TABLE\s+\w+\s+ADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS)/i.test(statement)) {
    statement = statement.replace(/(ALTER\s+TABLE\s+\w+\s+ADD\s+COLUMN\s+)/i, "$1IF NOT EXISTS ");
  }

  if (ignoreInsert) statement = `${statement.replace(/;\s*$/, "")} ON CONFLICT DO NOTHING`;

  let index = 0;
  return statement.replace(/\?/g, () => `$${++index}`);
}

module.exports = { PostgresSyncDatabase };
